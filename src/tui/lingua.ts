// Lingua dell'interfaccia OpenTUI. È una preferenza locale, non appartiene
// alla sessione o al progetto: riaprendo Continuity resta quella scelta.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
// Nei file .ts il compilatore della TUI non applica l'alias dei file JSX:
// l'entrypoint Node di solid-js è SSR e non notifica i componenti montati.
import { createSignal } from "solid-js/dist/solid.js";

import { fileInterfaccia, leggiLingua, linguaDiSerie, type Lingua } from "../core/lingua.js";
export { leggiLingua, type Lingua };

const [lingua, setLingua] = createSignal<Lingua>(linguaDiSerie());
export { lingua };

export function impostaLingua(cartellaDati: string, valore: Lingua) {
  let attuale: Record<string, unknown> = {};
  try {
    attuale = JSON.parse(readFileSync(fileInterfaccia(cartellaDati), "utf8"));
  } catch {}
  mkdirSync(cartellaDati, { recursive: true, mode: 0o700 });
  writeFileSync(fileInterfaccia(cartellaDati), JSON.stringify({ ...attuale, lingua: valore }, null, 2) + "\n", { mode: 0o600 });
  setLingua(valore);
}

export function inizializzaLingua(cartellaDati: string) {
  setLingua(leggiLingua(cartellaDati));
}

