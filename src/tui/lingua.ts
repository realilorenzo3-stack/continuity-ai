let nomiScelti = new Set<string>();
export function ricordaNomiScelti(config: any) {
  if (!config || (!Array.isArray(config.flussi) && !Array.isArray(config.ruoli))) return;
  nomiScelti = new Set(
    [...(config.flussi ?? []), ...(config.ruoli ?? [])]
      .filter((x: any) => x && !x.predefinito && typeof x.nome === "string")
      .map((x: any) => x.nome),
  );
}

